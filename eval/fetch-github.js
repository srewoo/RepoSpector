#!/usr/bin/env node
/**
 * Build an evaluation corpus from real, merged, human-reviewed public PRs.
 *
 *   node eval/fetch-github.js --out eval/corpus/public-prs.json --limit 8
 *
 * Why public PRs: they need no credential to justify, they can be re-fetched by
 * anyone checking a number, and the human review comments on them are genuine
 * ground truth for recall. The private-corpus path (eval/README.md) measures
 * the code the team actually writes; this one measures reproducibly.
 *
 * Rate limits are the binding constraint. Unauthenticated GitHub allows 60
 * requests/hour and one full PR fetch costs five, so this:
 *   - probes candidates with ONE request (`/pulls/{n}/comments`) and only
 *     fully fetches PRs that actually carry inline human review comments;
 *   - tracks the remaining budget from response headers and stops cleanly
 *     before exhausting it;
 *   - APPENDS to the output file, so a run that stops early can be topped up
 *     an hour later instead of starting over.
 *
 * Set GITHUB_TOKEN in .env to lift the limit to 5000/hour.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { env } from './lib/env.js';
import { toReferences, isBot } from './lib/humanComments.js';

/** Repos whose PRs reliably attract substantive inline review, in languages
 *  the reviewer has rule sets for (js/ts/py/go). */
const DEFAULT_REPOS = [
    'pandas-dev/pandas',
    'prometheus/prometheus',
    'vercel/next.js',
    'apache/airflow',
    'grafana/grafana',
];

/** Keep a PR only if it has at least this many locatable human comments. */
const MIN_HUMAN_COMMENTS = 2;
/** Skip PRs too large to review meaningfully inside one eval run. */
const MAX_FILES = 20;
/**
 * Stop before the budget is gone. A full fetch commits to five requests per PR,
 * so it must reserve enough to finish the one in flight; backfill costs exactly
 * one request per case and lowers this to 1 (see `backfillThreads`).
 */
const RESERVE_REQUESTS = 6;
const budgetReserve = { value: RESERVE_REQUESTS };

function parseArgs(argv) {
    const args = { out: 'eval/corpus/public-prs.json', limit: 8, repos: DEFAULT_REPOS, perRepo: 25 };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--out') args.out = argv[++i];
        else if (a === '--limit') args.limit = Number(argv[++i]);
        else if (a === '--repos') args.repos = argv[++i].split(',').map(s => s.trim()).filter(Boolean);
        else if (a === '--backfill-threads') args.backfill = true;
        else if (a === '--help' || a === '-h') args.help = true;
        else throw new Error(`Unknown argument: ${a}`);
    }
    return args;
}

const vars = env();
const TOKEN = vars.GITHUB_TOKEN || vars.GH_TOKEN || null;
const HEADERS = {
    Accept: 'application/vnd.github.v3+json',
    'User-Agent': 'RepoSpector-eval',
    ...(TOKEN ? { Authorization: `token ${TOKEN}` } : {}),
};

const budget = { remaining: Infinity, limit: Infinity, used: 0 };

async function gh(path) {
    if (budget.remaining <= budgetReserve.value) {
        const e = new Error('rate-limit reserve reached');
        e.code = 'BUDGET';
        throw e;
    }
    const res = await fetch(`https://api.github.com${path}`, { headers: HEADERS });
    budget.used++;
    const remaining = res.headers.get('x-ratelimit-remaining');
    const limit = res.headers.get('x-ratelimit-limit');
    if (remaining != null) budget.remaining = Number(remaining);
    if (limit != null) budget.limit = Number(limit);

    if (res.status === 403 && budget.remaining === 0) {
        const e = new Error('GitHub rate limit exhausted');
        e.code = 'BUDGET';
        throw e;
    }
    if (!res.ok) throw new Error(`GitHub ${res.status} on ${path}`);
    return res.json();
}

/** Existing cases, so a re-run tops the corpus up instead of replacing it. */
function loadExisting(path) {
    if (!existsSync(path)) return [];
    try {
        const raw = JSON.parse(readFileSync(path, 'utf8'));
        return Array.isArray(raw) ? raw : (raw.cases ?? []);
    } catch {
        return [];
    }
}

function save(path, cases) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, `${JSON.stringify({
        _comment: 'Generated by eval/fetch-github.js from public merged PRs. Gitignored.',
        generator: 'eval/fetch-github.js',
        cases,
    }, null, 2)}\n`);
}

/**
 * Re-read only the comment lists of already-cached cases, to add thread
 * provenance to a corpus fetched before `inReplyTo` was captured.
 *
 * One request per case, no PR detail or file re-fetch — cheap enough to run on
 * a nearly-exhausted anonymous budget rather than discarding the corpus.
 */
async function backfillThreads(outPath, cases) {
    // One request per case, nothing multi-step to strand halfway.
    budgetReserve.value = 1;
    let updated = 0;
    for (const kase of cases) {
        const [repo, number] = kase.id.split('#');
        let comments;
        try {
            comments = await gh(`/repos/${repo}/pulls/${number}/comments?per_page=100`);
        } catch (e) {
            if (e.code === 'BUDGET') { console.log(`Stopped: ${e.message}`); break; }
            console.log(`  ${kase.id}: ${e.message}`);
            continue;
        }
        const human = comments.filter(c => c.path && !isBot(c.user?.login));
        const before = kase.humanComments.filter(h => h.substantive).length;
        kase.humanComments = toReferences(human.map(c => ({
            path: c.path,
            line: c.line ?? c.original_line,
            body: c.body,
            author: c.user?.login,
            inReplyTo: c.in_reply_to_id ?? null,
        })));
        const after = kase.humanComments.filter(h => h.substantive).length;
        console.log(`  ${kase.id}: ${before} → ${after} substantive (thread roots only)`);
        updated++;
        save(outPath, cases);
    }
    console.log(`\nBackfilled ${updated} case(s).`);
}

async function main() {
    const args = parseArgs(process.argv.slice(2));
    if (args.help) {
        console.log('Usage: node eval/fetch-github.js [--out <file>] [--limit <n>] [--repos a/b,c/d]');
        return;
    }

    const outPath = resolve(args.out);
    const cases = loadExisting(outPath);
    const have = new Set(cases.map(c => c.id));
    console.log(`Corpus: ${cases.length} case(s) already cached at ${args.out}`);
    console.log(`Auth: ${TOKEN ? 'GITHUB_TOKEN (5000/hr)' : 'anonymous (60/hr) — set GITHUB_TOKEN in .env to raise'}\n`);

    if (args.backfill) {
        await backfillThreads(outPath, cases);
        save(outPath, cases);
        console.log(`Requests used: ${budget.used}  remaining: ${budget.remaining}`);
        return;
    }

    let added = 0;
    try {
        for (const repo of args.repos) {
            if (added >= args.limit) break;

            const list = await gh(`/repos/${repo}/pulls?state=closed&sort=updated&direction=desc&per_page=${args.perRepo}`);
            const merged = list.filter(p => p.merged_at);
            console.log(`${repo}: ${merged.length} merged PR(s) to probe  [budget ${budget.remaining}/${budget.limit}]`);

            for (const pr of merged) {
                if (added >= args.limit) break;
                const id = `${repo}#${pr.number}`;
                if (have.has(id)) continue;

                // ONE request decides whether this PR is worth four more.
                let comments;
                try {
                    comments = await gh(`/repos/${repo}/pulls/${pr.number}/comments?per_page=100`);
                } catch (e) {
                    if (e.code === 'BUDGET') throw e;
                    continue;
                }

                const human = comments.filter(c => c.path && !isBot(c.user?.login));
                if (human.length < MIN_HUMAN_COMMENTS) continue;

                let detail;
                let files;
                try {
                    detail = await gh(`/repos/${repo}/pulls/${pr.number}`);
                    if ((detail.changed_files ?? 0) > MAX_FILES) {
                        console.log(`  skip ${id}: ${detail.changed_files} files (> ${MAX_FILES})`);
                        continue;
                    }
                    files = await gh(`/repos/${repo}/pulls/${pr.number}/files?per_page=100`);
                } catch (e) {
                    if (e.code === 'BUDGET') throw e;
                    continue;
                }

                const withPatch = files.filter(f => f.patch && f.status !== 'removed');
                if (withPatch.length === 0) continue;

                const references = toReferences(human.map(c => ({
                    path: c.path,
                    line: c.line ?? c.original_line,
                    body: c.body,
                    author: c.user?.login,
                    // Distinguishes a thread ROOT from its replies. Without it
                    // one disputed issue counts four times in the recall
                    // denominator — see eval/lib/humanComments.js.
                    inReplyTo: c.in_reply_to_id ?? null,
                })));
                const substantive = references.filter(r => r.substantive).length;
                if (substantive < MIN_HUMAN_COMMENTS) {
                    console.log(`  skip ${id}: only ${substantive} substantive comment(s)`);
                    continue;
                }

                cases.push({
                    id,
                    url: detail.html_url,
                    // Everything the review pipeline needs, in the shape
                    // PullRequestService.normalizeGitHubPR produces — so the
                    // runner exercises the real code path without re-fetching.
                    prData: {
                        platform: 'github',
                        number: detail.number,
                        title: detail.title,
                        description: (detail.body || '').slice(0, 4000),
                        state: detail.state,
                        isDraft: false,
                        merged: true,
                        author: { login: detail.user?.login },
                        branches: {
                            source: detail.head?.ref,
                            target: detail.base?.ref,
                            targetRepo: repo,
                        },
                        headSha: detail.head?.sha ?? null,
                        baseSha: detail.base?.sha ?? null,
                        stats: {
                            additions: detail.additions ?? 0,
                            deletions: detail.deletions ?? 0,
                            changedFiles: detail.changed_files ?? withPatch.length,
                            commits: detail.commits ?? 0,
                        },
                        labels: (detail.labels || []).map(l => l.name),
                        files: withPatch.map(f => ({
                            filename: f.filename,
                            status: f.status,
                            additions: f.additions,
                            deletions: f.deletions,
                            patch: f.patch,
                        })),
                        commits: [],
                        url: detail.html_url,
                    },
                    humanComments: references,
                    // Filled in by eval/run.js, adjudicated by a human.
                    predictions: [],
                    adjudications: [],
                });
                have.add(id);
                added++;
                console.log(`  + ${id}  ${withPatch.length} file(s), ${substantive} substantive comment(s)  [budget ${budget.remaining}]`);
                save(outPath, cases);
            }
        }
    } catch (e) {
        if (e.code !== 'BUDGET') throw e;
        console.log(`\nStopped early: ${e.message}. ${cases.length} case(s) cached — re-run after the limit resets to top up.`);
    }

    save(outPath, cases);
    console.log(`\n${added} new case(s); ${cases.length} total in ${args.out}`);
    console.log(`Requests used: ${budget.used}  remaining: ${budget.remaining}`);
}

main().catch((e) => {
    console.error(`\n${e.message}`);
    process.exit(1);
});
